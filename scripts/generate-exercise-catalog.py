"""Verify curated activity codes against the primary 2024 Compendium tables.
Only numeric facts, source references and our Chinese labels go into the app.
"""
import html
import json
import re
import sys
import urllib.request
from pathlib import Path
from concurrent.futures import ThreadPoolExecutor

sys.stdout.reconfigure(encoding='utf-8')
ROOT = Path(__file__).resolve().parent.parent
selection = json.loads((ROOT / 'scripts/exercise-selection.json').read_text(encoding='utf-8'))

def fetch(slug):
    cache = ROOT / '.tools' / f'compendium-{slug}.html'
    if not cache.exists():
        cache.write_bytes(urllib.request.urlopen(f'https://pacompendium.com/{slug}/', timeout=30).read())
    facts = {}
    for row in re.findall(r'<tr\b[^>]*>(.*?)</tr>', cache.read_text(encoding='utf-8'), re.S):
        cells = [html.unescape(re.sub(r'<[^>]+>', '', text)).strip() for text in re.findall(r'<td\b[^>]*>(.*?)</td>', row, re.S)]
        if len(cells) >= 3 and re.fullmatch(r'\d{5}', cells[0]):
            facts[cells[0]] = float(cells[1])
    assert facts, f'No source rows in {slug}'
    return slug, facts

with ThreadPoolExecutor(max_workers=6) as pool:
    sources = dict(pool.map(fetch, sorted({row[0] for row in selection})))
catalog = []
for slug, code, name, aliases, category, group, distance, steps in selection:
    assert code in sources[slug], f'Unknown code {slug} {code} {name}'
    catalog.append(dict(code=code, met=sources[slug][code], name=name, aliases=aliases, category=category, group=group,
                        distanceKind=distance, countsSteps=steps, reference=f'https://pacompendium.com/{slug}/'))
assert len({x['code'] for x in catalog}) == len(catalog)
all_names = [name for item in catalog for name in [item['name']] + item['aliases']]
assert len(all_names) == len(set(all_names)), 'Ambiguous exercise aliases'
assert all(1 <= x['met'] <= 30 for x in catalog)
(ROOT / 'android/app/src/main/assets/exercises.json').write_text(json.dumps(catalog, ensure_ascii=False, indent=2), encoding='utf-8')

def literal(value):
    return json.dumps(value, ensure_ascii=False).replace('$', '\\$')

lines = []
for item in catalog:
    aliases = ', '.join(literal(x) for x in item['aliases'])
    lines.append(f'        ExerciseType({literal(item["name"])}, {item["met"]}, {literal(item["code"])}, listOf({aliases}), '
                 f'{literal(item["category"])}, {literal(item["group"])}, {literal(item["reference"])}, '
                 f'{literal(item["distanceKind"])}, {str(item["countsSteps"]).lower()}),')
source = '''package com.lrh.healthvivo.fitness

// Generated by scripts/generate-exercise-catalog.py; do not edit numeric source values here.
object ExerciseLibrary {
    val items = listOf(
''' + '\n'.join(lines) + '''
    )
    val groups = items.map { it.group }.distinct()
    fun match(name: String) = items.firstOrNull { it.name == name.trim() || name.trim() in it.aliases }
    fun search(query: String, group: String? = null) = items.filter { item ->
        (group == null || item.group == group) && (listOf(item.name) + item.aliases).any { it.contains(query.trim(), ignoreCase = true) }
    }
}
'''
(ROOT / 'android/app/src/main/java/com/lrh/healthvivo/fitness/ExerciseLibrary.kt').write_text(source, encoding='utf-8')
print(f'Generated {len(catalog)} verified exercise types')
